#!/usr/bin/env node
'use strict';
/**
 * _build/stamp.js — write app/version.js for a release.
 *
 *   node _build/stamp.js 1.1.0     # set the version and stamp the time
 *   node _build/stamp.js           # keep the version, restamp the time
 *
 * The (i) button in the corner reads this file, so it is how you tell which
 * build you are looking at. Run it before you push a change you want to
 * identify later.
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'app', 'version.js');

const previous = (() => {
  try {
    const src = fs.readFileSync(OUT, 'utf8');
    const m = /version:\s*'([^']+)'/.exec(src);
    return m ? m[1] : '1.0.0';
  } catch (e) { return '1.0.0'; }
})();

const version = process.argv[2] || previous;
if (!/^\d+\.\d+\.\d+$/.test(version)) {
  console.error(`version must look like 1.2.3, got "${version}"`);
  process.exit(2);
}

const built = new Date().toISOString();
const body = `/* Generated by _build/stamp.js — do not edit by hand.
   Run \`node _build/stamp.js <version>\` before pushing a release. */
window.APP_BUILD = { version: '${version}', built: '${built}' };
`;
fs.writeFileSync(OUT, body);
console.log(`app/version.js  version ${version}  built ${built}`);
