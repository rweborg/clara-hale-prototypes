#!/usr/bin/env python3
"""
_build/plates.py — turn raw portraits into "plates": the treated images the case
actually shows.

The portraits are generated by an image model, so on their own they share one
look — same light, same grade, same flat rectangle — which reads as AI. The case
declares a provenance for each one (cases/<id>/case.js -> portraits), and this
script renders that provenance into the image: the grade, the paper, and the
capture artefact that a photo from that source would actually carry.

    snapshot   warm, a little blown out, vignette, white print border, film date
    id         flat and neutral, thin border, name band along the bottom
    directory  sepia, softer, double border, serif caption
    school     warm neutral, thin white border, caption strip
    phone      saturated, faint screen glare, no border
    cctv       green monochrome, scanlines, timestamp bar

    python3 _build/plates.py [--dry-run]

Writes assets/plates/<person>.jpg and points the case's art at them.
The raw portraits stay untouched as source.
"""

import json
import os
import re
import sys

from PIL import Image, ImageDraw, ImageFilter, ImageFont

try:
    from reality import degrade as reality_degrade
except Exception:  # the pass is optional; plates still render without it
    reality_degrade = None
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CASES = os.path.join(ROOT, 'cases')
OUT = os.path.join(ROOT, 'assets', 'plates')

FONT = '/System/Library/Fonts/Helvetica.ttc'
FONT_BOLD = '/System/Library/Fonts/Helvetica.ttc'


def font(size, bold=False):
    try:
        return ImageFont.truetype(FONT, size, index=1 if bold else 0)
    except Exception:
        return ImageFont.load_default()


def grade(im, sat=1.0, warm=(1.0, 1.0, 1.0), contrast=1.0, gamma=1.0, vignette=0.0, mono=None):
    a = np.asarray(im.convert('RGB')).astype(np.float32) / 255.0
    if mono == 'green':
        g = a @ np.array([0.299, 0.587, 0.114], dtype=np.float32)
        a = np.dstack([g * 0.72, g * 1.02, g * 0.80])
    else:
        lum = a @ np.array([0.299, 0.587, 0.114], dtype=np.float32)
        a = np.clip(lum[..., None] + (a - lum[..., None]) * sat, 0, 1)
        a = a * np.array(warm, dtype=np.float32)
    a = np.clip((a - 0.5) * contrast + 0.5, 0, 1)
    if gamma != 1.0:
        a = np.power(a, gamma)
    if vignette > 0:
        h, w = a.shape[:2]
        y, x = np.ogrid[:h, :w]
        d = np.sqrt(((x - w / 2) / (w / 2)) ** 2 + ((y - h / 2) / (h / 2)) ** 2)
        a = a * np.clip(1 - vignette * np.clip(d - 0.55, 0, 1) ** 1.6, 0, 1)[..., None]
    return Image.fromarray((np.clip(a, 0, 1) * 255).astype(np.uint8))


def finish(im, grain=0.05, soften=0.6):
    """Break the too-clean sheen a generated image has: grain, a touch of
    softness, then a little sharpening back so it reads as a photograph."""
    im = im.filter(ImageFilter.GaussianBlur(soften))
    im = im.filter(ImageFilter.UnsharpMask(radius=1.4, percent=42, threshold=3))
    if grain > 0:
        a = np.asarray(im).astype(np.float32)
        noise = np.random.default_rng(7).normal(0, 255 * grain, a.shape[:2])[..., None]
        a = np.clip(a + noise, 0, 255)
        im = Image.fromarray(a.astype(np.uint8))
    return im


def roughen(im, zoom=1.07, dx=0.05, dy=0.02, down=680, ca=1.1):
    """Take the studio gloss off a generated portrait: crop it off-centre, throw
    resolution away and get it back, and split the colour channels slightly the
    way a cheap lens does. A model cannot be asked for bad optics."""
    w, h = im.size
    cw, ch = int(w / zoom), int(h / zoom)
    x0 = max(0, min(w - cw, int((w - cw) / 2 + dx * cw)))
    y0 = max(0, min(h - ch, int((h - ch) / 2 + dy * ch)))
    im = im.crop((x0, y0, x0 + cw, y0 + ch))
    if down and im.width > down:
        small = im.resize((down, max(1, int(im.height * down / im.width))), Image.LANCZOS)
        im = small.resize((cw, ch), Image.LANCZOS)
    if ca:
        r, g, b = im.split()
        r = r.transform(r.size, Image.AFFINE, (1, 0, -ca, 0, 1, 0))
        b = b.transform(b.size, Image.AFFINE, (1, 0, ca, 0, 1, 0))
        im = Image.merge('RGB', (r, g, b))
    return im


def add_scanlines(im, gap=4, strength=0.10):
    a = np.asarray(im).astype(np.float32)
    a[::gap] *= (1 - strength)
    return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8))


# Which bad camera each source was photographed with.
REALITY = {
    'snapshot': 'tungsten',
    'phone': 'tungsten',
    'id': 'fluorescent',
    'school': 'fluorescent',
    'directory': 'tungsten',
    'cctv': 'cctv',
    'scene': 'overcast',
}


def plate(src, rec):
    """Render one provenance into a finished plate."""
    im = Image.open(src).convert('RGB')
    w, h = im.size
    kind = rec['type']
    name = rec.get('name', '')

    if kind == 'snapshot':
        im = roughen(grade(im, sat=1.12, warm=(1.07, 1.0, 0.9), gamma=0.94, vignette=0.35))
        border = int(w * 0.035)
        out = Image.new('RGB', (w + border * 2, h + border * 2), (247, 244, 236))
        out.paste(im, (border, border))
        d = ImageDraw.Draw(out)
        d.text((out.width - border - int(w * 0.02), out.height - border - int(h * 0.045)),
               "SEP 12 '25", font=font(int(w * 0.032), True), fill=(214, 122, 60), anchor='rs')

    elif kind == 'id':
        im = grade(im, sat=0.55, warm=(1.0, 1.01, 1.04), contrast=1.06)
        band = int(h * 0.13)
        out = Image.new('RGB', (w, h + band), (232, 236, 241))
        out.paste(im, (0, 0))
        d = ImageDraw.Draw(out)
        d.line([(0, h), (w, h)], fill=(180, 190, 200), width=max(1, w // 300))
        d.text((int(w * 0.045), h + band // 2), name.upper(), font=font(int(w * 0.045), True),
               fill=(48, 60, 74), anchor='lm')
        d.text((w - int(w * 0.045), h + band // 2), 'COUNTY', font=font(int(w * 0.03)),
               fill=(120, 132, 146), anchor='rm')

    elif kind == 'directory':
        im = grade(im, sat=0.42, warm=(1.09, 1.0, 0.86), contrast=0.97, vignette=0.22)
        pad = int(w * 0.045)
        out = Image.new('RGB', (w + pad * 2, h + pad * 2 + int(h * 0.08)), (243, 238, 228))
        out.paste(im, (pad, pad))
        d = ImageDraw.Draw(out)
        d.rectangle([pad // 2, pad // 2, out.width - pad // 2, out.height - pad // 2],
                    outline=(176, 160, 132), width=max(1, w // 260))
        d.text((out.width // 2, out.height - pad), name, font=font(int(w * 0.042)),
               fill=(92, 80, 62), anchor='mb')

    elif kind == 'school':
        im = grade(im, sat=0.92, warm=(1.03, 1.0, 0.96), contrast=1.04)
        border = int(w * 0.022)
        strip = int(h * 0.085)
        out = Image.new('RGB', (w + border * 2, h + border + strip), (250, 249, 246))
        out.paste(im, (border, border))
        d = ImageDraw.Draw(out)
        d.text((out.width // 2, out.height - strip // 2), name.upper(),
               font=font(int(w * 0.038), True), fill=(58, 58, 62), anchor='mm')

    elif kind == 'phone':
        im = roughen(grade(im, sat=1.18, warm=(1.02, 1.0, 1.0), contrast=1.03, vignette=0.12),
                    zoom=1.04, dx=-0.04, dy=0.03, down=720, ca=1.4)
        # faint screen glare across the top-left, like a phone held up
        hh, ww = im.size
        glare = Image.new('L', (ww, hh), 0)
        gd = ImageDraw.Draw(glare)
        gd.polygon([(0, 0), (int(ww * 0.55), 0), (0, int(hh * 0.5))], fill=46)
        glare = glare.filter(ImageFilter.GaussianBlur(ww * 0.06))
        white = Image.new('RGB', (ww, hh), (255, 255, 255))
        out = Image.composite(white, im, glare.point(lambda v: int(v * 0.5)))

    elif kind == 'cctv':
        im = grade(im, contrast=1.18, mono='green')
        im = add_scanlines(im, gap=max(2, h // 160), strength=0.10)
        out = im.copy()
        d = ImageDraw.Draw(out)
        d.text((int(w * 0.03), int(h * 0.025)), rec.get('stamp', '10:40:18 PM   CAM-02   RTE 9'),
               font=font(int(w * 0.028), True), fill=(214, 240, 214))

    else:  # scene, newspaper, flyer, mugshot — a plain photographic grade
        out = grade(im, sat=0.95, contrast=1.04)

    heavy = kind in ('snapshot', 'phone')
    out = finish(out, grain=0.050 if heavy else 0.035, soften=0.4)
    if reality_degrade:
        # The case says which bad camera took it and how badly it was shot;
        # fall back to the provenance default.
        preset = rec.get('tint') or REALITY.get(kind)
        if preset:
            out = reality_degrade(out, preset, tilt=0, quality=rec.get('quality', 'ok'))
    return out, (78 if heavy else 86)


def main():
    dry = '--dry-run' in sys.argv
    os.makedirs(OUT, exist_ok=True)
    made = []

    for case_id in sorted(os.listdir(CASES)):
        case_file = os.path.join(CASES, case_id, 'case.js')
        if not os.path.exists(case_file):
            continue
        src = open(case_file, encoding='utf-8').read()
        m = re.search(r'(?m)^const PORTRAITS = (\{.*?\n\});$', src, re.S)
        if not m:
            continue
        portraits = json.loads(m.group(1))
        art = re.search(r'(?m)^const ART = (\{.*?\n\});$', src, re.S)
        if not art:
            continue
        art_map = json.loads(art.group(1))

        for key, rec in portraits.items():
            # Approved art is shipped as-is. The pipeline must never quietly
            # re-grade a cast that has been signed off.
            if rec.get('locked'):
                print(f'  lock   {key:<10} approved, left alone')
                continue
            # Always treat the raw portrait, never the plate: art already points
            # at the plate after the first run, and re-treating it compounds the
            # border, grade and grain.
            raw = rec.get('file') or art_map.get(key)
            if not raw:
                continue
            full = os.path.join(ROOT, raw)
            if not os.path.exists(full):
                print(f'  ! missing source for {key}: {raw}')
                continue
            out_name = key[2:] if key.startswith('p_') else key
            out_rel = f'assets/plates/{out_name}.jpg'
            out_full = os.path.join(ROOT, out_rel)
            img, quality = plate(full, rec)
            if not dry:
                img.save(out_full, 'JPEG', quality=quality, optimize=True)
            art_map[key] = out_rel
            made.append((key, rec['type'], out_rel))

        if not dry:
            new_art = 'const ART = ' + json.dumps(art_map, indent=2, ensure_ascii=False) + ';'
            src = src[:art.start()] + new_art + src[art.end():]
            open(case_file, 'w', encoding='utf-8').write(src)

    for key, kind, rel in made:
        print(f'  {key:<10} {kind:<10} -> {rel}')
    print(f'\n{len(made)} plates ' + ('measured' if dry else 'written'))


if __name__ == '__main__':
    main()
